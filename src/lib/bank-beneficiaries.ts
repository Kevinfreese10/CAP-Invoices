export function normalizeSupplierKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/\.\.\.$/, '')
    .replace(/\(pty\)\s*ltd/gi, '')
    .replace(/pty\s*ltd/gi, '')
    .replace(/\(pty\)/gi, '')
    .replace(/pty/gi, '')
    .replace(/ltd/gi, '')
    .replace(/cc/gi, '')
    .replace(/inc/gi, '')
    .replace(/t\/a.*/gi, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

/**
 * Resolves the exact Investec bank beneficiary name for a given supplier (always full untruncated name).
 */
export function getBankBeneficiary(
  supplierName: string,
  overrides?: Record<string, string>
): string | null {
  if (!supplierName) return null;
  const trimmed = supplierName.trim();

  let resolved: string | null = null;

  // 1. Direct check in overrides
  if (overrides && overrides[trimmed]) {
    resolved = overrides[trimmed];
  } else if (DEFAULT_BENEFICIARY_MAP[trimmed]) {
    // 2. Direct check in default map
    resolved = DEFAULT_BENEFICIARY_MAP[trimmed];
  } else {
    const norm = normalizeSupplierKey(trimmed);
    if (!norm) return null;

    // 3. Normalized check in overrides
    if (overrides) {
      for (const [k, v] of Object.entries(overrides)) {
        if (normalizeSupplierKey(k) === norm) {
          resolved = v;
          break;
        }
      }
    }

    // 4. Normalized check in default map
    if (!resolved) {
      for (const [k, v] of Object.entries(DEFAULT_BENEFICIARY_MAP)) {
        if (normalizeSupplierKey(k) === norm) {
          resolved = v;
          break;
        }
      }
    }

    // 5. Prefix or substring match against Investec beneficiary list
    if (!resolved) {
      const match = INVESTEC_BENEFICIARIES.find((b) => {
        const normB = normalizeSupplierKey(b);
        return normB.length >= 4 && (norm.startsWith(normB) || normB.startsWith(norm) || norm.includes(normB) || normB.includes(norm));
      });
      if (match) resolved = match;
    }
  }

  if (resolved) {
    // Safety check: ensure any trailing ... is stripped and mapped to full name if in expansions
    let finalStr = resolved.trim();
    if (UNTRUNCATED_EXPANSIONS[finalStr]) {
      finalStr = UNTRUNCATED_EXPANSIONS[finalStr];
    }
    return finalStr.replace(/\.\.\.+$/, '').trim();
  }

  return null;
}
