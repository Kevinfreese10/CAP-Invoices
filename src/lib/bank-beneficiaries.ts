export function normalizeSupplierKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/\.\.\.$/, '')
    .replace(/\(pty\)\s*ltd/gi, '')
    .replace(/pty\s*ltd/gi, '')
    .replace(/\(pty\)/gi, '')
    .replace(/pty/gi, '')
    .replace(/ltd/gi, '')
    .replace(/cc/gi, '')
    .replace(/inc/gi, '')
    .replace(/t\/a.*/gi, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

/**
 * Resolves the exact Investec bank beneficiary name for a given supplier.
 */
export function getBankBeneficiary(
  supplierName: string,
  overrides?: Record<string, string>
): string | null {
  if (!supplierName) return null;
  const trimmed = supplierName.trim();

  // 1. Direct check in overrides
  if (overrides && overrides[trimmed]) {
    return overrides[trimmed];
  }

  // 2. Direct check in default map
  if (DEFAULT_BENEFICIARY_MAP[trimmed]) {
    return DEFAULT_BENEFICIARY_MAP[trimmed];
  }

  const norm = normalizeSupplierKey(trimmed);
  if (!norm) return null;

  // 3. Normalized check in overrides
  if (overrides) {
    for (const [k, v] of Object.entries(overrides)) {
      if (normalizeSupplierKey(k) === norm) {
        return v;
      }
    }
  }

  // 4. Normalized check in default map
  for (const [k, v] of Object.entries(DEFAULT_BENEFICIARY_MAP)) {
    if (normalizeSupplierKey(k) === norm) {
      return v;
    }
  }

  // 5. Prefix or truncated match against Investec beneficiary list
  const prefixMatch = INVESTEC_BENEFICIARIES.find((b) => {
    const normB = normalizeSupplierKey(b);
    return normB.length >= 4 && (norm.startsWith(normB) || normB.startsWith(norm));
  });
  if (prefixMatch) return prefixMatch;

  // 6. Substring match
  const subMatch = INVESTEC_BENEFICIARIES.find((b) => {
    const normB = normalizeSupplierKey(b);
    return normB.length >= 5 && (norm.includes(normB) || normB.includes(norm));
  });
  if (subMatch) return subMatch;

  return null;
}
